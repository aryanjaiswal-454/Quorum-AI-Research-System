from langchain.agents import create_agent
from langchain_groq import ChatGroq
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser
from tools import web_search, scrape_url
import os
from dotenv import load_dotenv
load_dotenv()

# Setting up the LLM (Language Model) using the Groq API with the provided API key and a temperature setting for response variability.
llm = ChatGroq(model="openai/gpt-oss-120b",api_key = os.getenv("GROQ_API_KEY"),temperature=0)


# Web Search Agent: This agent is designed to perform web searches and return relevant information.
def build_search_agent():
    return create_agent(
        model=llm,
        tools=[web_search]
    )
    
    
# Reader Agent: This agent is designed to scrape and read content from a given URL for deeper understanding.
def build_reader_agent():
    return create_agent(
        model=llm,
        tools=[scrape_url]
    )   
    
    
# Writer Chain: This chain takes the research gathered by the agents and compiles it into a structured research report.
writer_prompt = ChatPromptTemplate.from_messages([
    ("system", "You are an expert research writer. Write clear, structured and insightful reports."),
    ("human", """Write a detailed research report on the topic below.

    Topic: {topic}

    Research Gathered:
    {research}

    Structure the report as:
    - Introduction
    - Key Findings (minimum 3 well-explained points)
    - Conclusion
    - Sources (list all URLs found in the research)

    Be detailed, factual and professional."""),
    ])

writer_chain = writer_prompt | llm | StrOutputParser()


# Critic Chain: This chain evaluates the research report generated by the writer chain, providing constructive feedback and a score based on the quality of the report.
critic_prompt = ChatPromptTemplate.from_messages([
    ("system", "You are a sharp and constructive research critic. Be honest and specific."),
    ("human", """Review the research report below and evaluate it strictly.

    Report:
    {report}

    Respond in this exact format:

    Score: X/10

    Strengths:
    - ...
    - ...

    Areas to Improve:
    - ...
    - ...

    One line verdict:
    ..."""),
    ])

critic_chain = critic_prompt | llm | StrOutputParser()